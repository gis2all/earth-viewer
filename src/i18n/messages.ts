const catalogs: Record<Locale, Record<MessageKey, string>> = {
  'zh-CN': zh,
  en,
}

export const MESSAGE_KEYS = Object.keys(zh) as MessageKey[]

export function getMessageTemplate(locale: Locale, key: MessageKey): string {
  return catalogs[locale][key]
}

export function translate(locale: Locale, key: MessageKey, params?: Record<string, string | number>): string {
  const template = catalogs[locale][key] ?? catalogs['zh-CN'][key]
  if (!params) return template
  return template.replace(/\{(\w+)\}/g, (match, name: string) => {
    const value = params[name]
    return value === undefined ? match : String(value)
  })
}

export function translateAppMessage(locale: Locale, message: AppMessage): string {
  return translate(locale, message.key, message.params)
}
